namespace HCA.AdminMetrics.Api.Constants;

/// <summary>
/// Defines HTTP header names and related authorization constants used by the API.
/// </summary>
public static class RequestHeaders
{
    /// <summary>
    /// Gets the authorization header name.
    /// </summary>
    public const string Authorization = "Authorization";

    /// <summary>
    /// Gets the JWT token format label.
    /// </summary>
    public const string JWT = "JWT";

    /// <summary>
    /// Gets the bearer authentication scheme name.
    /// </summary>
    public const string Bearer = "Bearer";
}
